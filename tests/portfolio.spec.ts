import { expect, test } from '@playwright/test'

test('loads core navigation and the interactive twin', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('console', (msg) => { if (msg.type() === 'error') errors.push(msg.text()) })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Engineering the physical world/i })).toBeVisible()
  await expect(page.getByTestId('warehouse-canvas')).toBeVisible()
  const navigation = page.getByRole('navigation', { name: 'Primary navigation' })
  if (await navigation.isVisible()) await page.getByRole('link', { name: 'Evidence', exact: true }).click()
  else await page.goto('/#evidence')
  await expect(page.getByRole('heading', { name: 'Systems work, in the open.' })).toBeInViewport()
  await expect(page.getByRole('link', { name: /agent-cli-lab/ })).toHaveAttribute('href', 'https://github.com/TuanKietTran/agent-cli-lab')
  expect(errors, `console errors in ${testInfo.project.name}`).toEqual([])
})

test('simulation controls update state', async ({ page }) => {
  await page.goto('/#twin')
  const pause = page.getByRole('button', { name: /pause/i })
  await expect(pause).toBeVisible()
  await pause.click()
  await expect(page.getByRole('button', { name: /resume/i })).toBeVisible()
  await page.getByRole('button', { name: '2×' }).click()
  await expect(page.getByRole('button', { name: '2×' })).toHaveClass(/active/)
  await page.getByRole('slider', { name: 'Robot workload' }).fill('18')
  await expect(page.getByText('18 units')).toBeVisible()
  await page.getByRole('button', { name: 'aisle' }).click()
  await expect(page.getByRole('button', { name: 'aisle' })).toHaveClass(/active/)
  await page.getByRole('button', { name: 'overview' }).click()
  const canvas = page.getByTestId('warehouse-canvas')
  const box = await canvas.boundingBox()
  if (box) {
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width / 2 + 80, box.y + box.height / 2 + 20, { steps: 5 })
    await page.mouse.up()
  }
  await expect(page.getByTestId('selection-details')).toContainText('None')
})

test('lazy GPU benchmark initializes a real rendering backend', async ({ page }, testInfo) => {
  await page.goto('/#benchmark')
  await page.getByTestId('load-benchmark').click()
  const benchmark = page.getByTestId('benchmark')
  await expect(benchmark).toBeVisible()
  const webGPUAvailable = await page.evaluate(async () => Boolean(navigator.gpu && await navigator.gpu.requestAdapter()))
  testInfo.annotations.push({ type: 'capability', description: webGPUAvailable ? 'WebGPU adapter available; WGSL path expected' : 'No WebGPU adapter; WebGL 2 fallback expected' })
  await page.getByRole('button', { name: /initialize benchmark/i }).click()
  const status = page.locator('.bench-message')
  if (webGPUAvailable) await expect(status).toContainText('Raw WebGPU/WGSL')
  else await expect(status).toContainText('WebGL 2 shader fallback')
  await expect(page.getByText(webGPUAvailable ? 'WebGPU' : 'WebGL 2', { exact: true })).toBeVisible()
  await expect(page.getByText(/fragment iterations/)).toBeVisible()
  await page.getByRole('button', { name: 'Burn-in' }).click()
  await expect(status).toContainText('Workload changed live: Burn-in · 64 fragment iterations')
  await expect(page.getByText('64 fragment iterations · fullscreen triangle')).toBeVisible()
  await benchmark.getByRole('button', { name: /pause/i }).click()
  const pausedDuration = await page.getByText('Duration').locator('..').locator('strong').textContent()
  await page.waitForTimeout(300)
  await expect(page.getByText('Duration').locator('..').locator('strong')).toHaveText(pausedDuration ?? '')
  await benchmark.getByRole('button', { name: /start/i }).click()
  await page.waitForTimeout(300)
  await benchmark.getByRole('button', { name: /pause/i }).click()
  await benchmark.getByRole('button', { name: /reset/i }).click()
  await expect(status).toContainText('resources released')
})

test('graphics-unavailable path preserves content', async ({ browser }) => {
  const context = await browser.newContext()
  await context.addInitScript(() => { HTMLCanvasElement.prototype.getContext = () => null })
  const page = await context.newPage()
  await page.goto('/')
  await expect(page.getByText('Warehouse simulation interface')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Built beyond the surface.' })).toBeVisible()
  await page.getByTestId('load-benchmark').click()
  await page.getByRole('button', { name: /initialize benchmark/i }).click()
  await expect(page.locator('.bench-message')).toContainText('Neither WebGPU nor WebGL 2')
  await context.close()
})

test('mobile layout has no horizontal overflow', async ({ page }) => {
  await page.goto('/')
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
  expect(overflow).toBeLessThanOrEqual(1)
  await expect(page.getByRole('heading', { name: /Engineering the physical world/i })).toBeVisible()
})
